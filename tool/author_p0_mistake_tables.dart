void main(List<String> args) {
  final dryRun = args.contains('--dry-run');
  final preview = _stringOption(args, '--preview=', '');
  final manifest =
      jsonDecode(File(manifestPath).readAsStringSync()) as Map<String, dynamic>;
  final lessons = <Map<String, dynamic>>[
    for (final rawCategory in manifest['categories'] as List<dynamic>)
      for (final raw in (rawCategory as Map)['lessons'] as List<dynamic>)
        (raw as Map).cast<String, dynamic>(),
  ];
  final byId = <String, Map<String, dynamic>>{
    for (final lesson in lessons) lesson['id'].toString(): lesson,
  };
  final invalid = <String>[
    for (final entry in curatedMistakeTables.entries)
      if (entry.value.length < 3 ||
          entry.value.any(
            (row) =>
                row.length != 3 ||
                row.any((cell) => cell.trim().isEmpty) ||
                row.any((cell) => cell.trim().length < 6) ||
                row.any(_hasUnescapedPipe),
          ))
        entry.key,
  ];
  if (invalid.isNotEmpty) {
    stderr.writeln('错误表数据不合法（行数不足、单元格为空或竖线未转义）：${invalid.join('、')}');
    exitCode = 3;
    return;
  }
  final unknown = curatedMistakeTables.keys
      .where((id) => !byId.containsKey(id))
      .toList();
  if (unknown.isNotEmpty) {
    stderr.writeln('错误表里有清单中不存在的课程：${unknown.join('、')}');
    exitCode = 4;
    return;
  }
  if (preview.isNotEmpty) {
    final lesson = byId[preview];
    if (lesson == null) {
      stderr.writeln('找不到课程：$preview');
      exitCode = 2;
      return;
    }
    stdout.writeln(
      _sectionText(
        rewriteMistakeTable(
          File(lesson['file'].toString()).readAsStringSync(),
          lesson,
        ),
      ),
    );
    return;
  }
  final only = _stringOption(args, '--ids=', '')
      .split(',')
      .map((value) => value.trim())
      .where((value) => value.isNotEmpty)
      .toSet();
  var rewritten = 0;
  final skipped = <String>[];
  final coverage = <Map<String, dynamic>>[];
  for (final id in curatedMistakeTables.keys) {
    if (only.isNotEmpty && !only.contains(id)) continue;
    final lesson = byId[id]!;
    final file = File(lesson['file'].toString());
    final before = file.readAsStringSync();
    final after = rewriteMistakeTable(before, lesson);
    coverage.add(<String, dynamic>{
      'lesson_id': id,
      'file': lesson['file'],
      'rows': curatedMistakeTables[id]!.length,
      'has_note': before.contains('> 说明：本表由'),
      'would_rewrite': after != before,
    });
    if (after == before) continue;
    if (!after.contains(tableHeader)) {
      skipped.add(id);
      continue;
    }
    rewritten++;
    if (!dryRun) file.writeAsStringSync(after, flush: true);
  }
  if (skipped.isNotEmpty) {
    stderr.writeln('以下课程没有找到目标章节：${skipped.join('、')}');
  }
  stdout.writeln(
    '${dryRun ? '[dry-run] ' : ''}重写错误表 $rewritten 篇（数据 ${curatedMistakeTables.length} 门）',
  );
  // 覆盖率报告：记录 215 门课的易错点行数与说明行是否就位，便于复查。
  File(reportPath)
    ..createSync(recursive: true)
    ..writeAsStringSync(
      const JsonEncoder.withIndent('  ').convert(<String, dynamic>{
        'generated_at': DateTime.now().toUtc().toIso8601String(),
        'dry_run': dryRun,
        'lessons': curatedMistakeTables.length,
        'rewritten': rewritten,
        'missing_note': [
          for (final item in coverage)
            if (item['has_note'] != true) item['lesson_id'],
        ],
        'coverage': coverage,
      }),
      flush: true,
    );
}

/// 用本课易错点重建「常见错误与排查」，并写明这不是人工复核记录。
String rewriteMistakeTable(String markdown, Map<String, dynamic> lesson) {
  final rows = curatedMistakeTables[lesson['id'].toString()];
  if (rows == null) return markdown;
  final title = ((lesson['title'] as Map?)?['zh'] ?? lesson['id']).toString();
  final lines = markdown.split('\n');
  final range = _sectionRange(lines, markdownFenceMask(markdown));
  if (range == null) return markdown;
  // 旧章节里表格之外的正文（例如对照图、补充段落）必须原样保留，
  // 否则每次重写都会悄悄吃掉章节尾部的配图。
  final preserved = <String>[
    for (final line in lines.sublist(range.heading + 1, range.end))
      if (_isPreservedLine(line)) line.trimRight(),
  ];
  final output = <String>[
    ...lines.sublist(0, range.heading + 1),
    '',
    '> 说明：本表由《$title》的核心知识整理（$updatedAt），'
        '人工复核进度见 docs/content_review_batches.md。',
    '',
    tableHeader,
    separatorRow,
    for (final row in rows) '| ${row[0]} | ${row[1]} | ${row[2]} |',
    if (preserved.isNotEmpty) ...['', ...preserved],
    '',
    ...lines.sublist(range.end),
  ];
  return '${output.join('\n').trimRight()}\n';
}

/// 表格行、空行和本工具自己写的说明行会被重建，其余内容（配图、段落）保留。
bool _isPreservedLine(String line) {
  final trimmed = line.trim();
  if (trimmed.isEmpty) return false;
  if (trimmed.startsWith('|')) return false;
  if (trimmed.startsWith('> 说明：本表由')) return false;
  return true;
}

({int heading, int end})? _sectionRange(List<String> lines, List<bool> mask) {
  final headingPattern = RegExp('^##\\s+$sectionHeading\\s*\$');
  final sectionPattern = RegExp(r'^##\s+');
  var heading = -1;
  for (var index = 0; index < lines.length; index++) {
    if (mask[index]) continue;
    if (headingPattern.hasMatch(lines[index])) {
      heading = index;
      break;
    }
  }
  if (heading < 0) return null;
  var end = lines.length;
  for (var index = heading + 1; index < lines.length; index++) {
    if (mask[index]) continue;
    if (sectionPattern.hasMatch(lines[index])) {
      end = index;
      break;
    }
  }
  return (heading: heading, end: end);
}

String _sectionText(String markdown) {
  final lines = markdown.split('\n');
  final range = _sectionRange(lines, markdownFenceMask(markdown));
  if (range == null) return '(没有$sectionHeading章节)';
  return lines.sublist(range.heading, range.end).join('\n').trimRight();
}

/// 表格单元格里的竖线必须写成 \|，否则会把表格撑成多列。
bool _hasUnescapedPipe(String text) {
  for (var index = 0; index < text.length; index++) {
    if (text[index] != '|') continue;
    if (index > 0 && text[index - 1] == r'\') continue;
    return true;
  }
  return false;
}

String _stringOption(List<String> args, String prefix, String fallback) {
  for (final arg in args) {
    if (!arg.startsWith(prefix)) continue;
    return arg.substring(prefix.length);
  }
  return fallback;
}
