def _measure(text: str, size: int, bold: bool = False) -> int:
    """测量一行文字的像素宽度，用于提前拦住超框的文案。"""
    import generate_diagrams as base
    from PIL import Image, ImageDraw

    image = Image.new("RGB", (10, 10))
    draw = ImageDraw.Draw(image)
    return base.text_size(draw, text, base.font(size, bold=bold))[0]


def check_layout() -> list[str]:
    """检查标题、条目、阶段与关卡文字是否超出图形边界。"""
    from generate_p2_extra_diagrams import wrap_cn

    problems: list[str] = []
    for lesson_id, cfg in COMPARE.items():
        title_size = 32 if len(cfg["title"]) <= 24 else 28
        if _measure(cfg["title"], title_size, True) > 1120:
            problems.append(f"{lesson_id}: 标题超宽")
        if _measure(cfg["subtitle"], 18) > 1120:
            problems.append(f"{lesson_id}: 副标题超宽")
        for side in ("left", "right"):
            for item in cfg[side]:
                for line in wrap_cn(item, 27)[:2]:
                    if _measure(line, 19) > 482:
                        problems.append(f"{lesson_id}: {side} 条目超宽 - {line}")
        for footer in cfg["footers"]:
            if _measure(footer, 20) > 1120:
                problems.append(f"{lesson_id}: 脚注超宽 - {footer}")
    for lesson_id, cfg in FLOWS.items():
        count = len(cfg["stages"])
        box = int((1120 - 26 * (count - 1)) / count)
        for stage in cfg["stages"]:
            for line in stage.split("\n"):
                if _measure(line, 20, True) > box - 12:
                    problems.append(f"{lesson_id}: 阶段超宽 - {line}")
        for check in cfg["checks"]:
            for line in check.split("\n"):
                if _measure(line, 19) > 338:
                    problems.append(f"{lesson_id}: 关卡超宽 - {line}")
        for footer in cfg["footers"]:
            if _measure(footer, 20) > 1120:
                problems.append(f"{lesson_id}: 脚注超宽 - {footer}")
    return problems


def main() -> None:
    problems = check_layout()
    if problems:
        for problem in problems:
            print(f"文字超框：{problem}", file=sys.stderr)
        raise SystemExit(1)
    batch: dict[str, dict[str, str]] = {}
    for lesson_id, raw in {**COMPARE, **FLOWS}.items():
        config = dict(raw)
        alt = config.pop("alt")
        name = f"{PREFIX}{lesson_id}"
        if "stages" in config:
            flow_diagram(name=name, **config)
        else:
            compare_diagram(name=name, **config)
        batch[lesson_id] = {
            "image": f"images/{name}.webp",
            "alt": alt,
            "anchor": "本课小结",
        }
    BATCH.parent.mkdir(parents=True, exist_ok=True)
    BATCH.write_text(
        json.dumps(batch, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"生成 {len(batch)} 张补全配图，批次写入 {BATCH}")


if __name__ == "__main__":
    main()
